// ---------------------------------------------------------- file kinds
export function kindOf(item) {
  if (item.is_dir) return 'folder';
  const m = item.mime_type || '';
  const n = (item.name || '').toLowerCase();
  if (m.startsWith('image/')) return 'image';
  if (m.startsWith('video/')) return 'video';
  if (m.startsWith('audio/')) return 'audio';
  if (m === 'application/pdf' || n.endsWith('.pdf')) return 'pdf';
  if (m.includes('spreadsheet') || /\.(xlsx?|csv|ods)$/.test(n)) return 'sheet';
  if (m.includes('presentation') || /\.(pptx?|odp|key)$/.test(n)) return 'slides';
  if (m.includes('document') || m.includes('word') || /\.(docx?|odt|rtf)$/.test(n)) return 'doc';
  if (/zip|tar|rar|7z|compressed|gzip/.test(m) || /\.(zip|tar|gz|bz2|xz|7z|rar)$/.test(n)) return 'archive';
  if (m.startsWith('text/') || /\.(txt|md|json|xml|ya?ml|toml|log)$/.test(n)) return 'text';
  if (/\.(js|ts|py|rs|go|c|cpp|h|java|html|css|sh|rb|php)$/.test(n)) return 'code';
  return 'file';
}
const KIND_ICON = { folder: 'folder', image: 'image', video: 'video', audio: 'audio', pdf: 'file', sheet: 'file', slides: 'file', doc: 'file', archive: 'file', text: 'file', code: 'code', file: 'file' };
export const kindIcon = (item, cls = '') => `<span class="kind kind-${kindOf(item)} ${cls}">${icon(KIND_ICON[kindOf(item)])}</span>`;

export function previewKind(item) {
  const k = kindOf(item);
  if (k === 'image' && /^image\/(jpeg|png|gif|webp|svg\+xml|bmp|avif)$/.test(item.mime_type)) return 'image';
  if (k === 'video') return 'video';
  if (k === 'audio') return 'audio';
  if (k === 'text' || k === 'code') return item.size <= 1024 * 1024 ? 'text' : 'none';
  return 'none';
}

