// ------------------------------------------------------------- toasts
export function toast(msg, opts = {}) {
  const root = document.getElementById('toasts');
  const el = document.createElement('div');
  el.className = `toast ${opts.kind || ''}`;
  el.setAttribute('role', opts.kind === 'error' ? 'alert' : 'status');
  el.innerHTML = `<span>${esc(msg)}</span>${opts.action ? `<button class="toast-action">${esc(opts.action.label)}</button>` : ''}`;
  if (opts.action) $('.toast-action', el).addEventListener('click', () => { opts.action.run(); el.remove(); });
  root.appendChild(el);
  while (root.children.length > 4) root.firstChild.remove();
  setTimeout(() => el.classList.add('out'), opts.ms || (opts.kind === 'error' ? 7000 : 3500));
  setTimeout(() => el.remove(), (opts.ms || 3500) + 600);
}
